"""
Narrow-band vibration benchmark.

The handheld clips (meshflow, ostrich, running) are the wrong data class for a
vehicle-mounted camera. A human hand shakes across a broad band, 0-20 Hz, which
overlaps the deliberate motion and is the hardest case an IIR low-pass can face.
A rotor or engine produces a *narrow* band with a clear peak, which is the
easiest case. Measuring only on handheld footage understates what the method
will do on the target platform.

Publicly available drone footage is almost all gimbal-stabilized, so the
vibration we want to measure has already been removed in hardware. Injecting a
known narrow-band vibration into real footage is the practical alternative: real
texture and lighting, exact ground truth, and a frequency we can sweep.

Caveat worth stating in any report that uses this: at 30 fps only components
below 15 Hz are observable. Real rotor vibration typically sits well above that
and will alias into the visible band as broadband noise -- which is the hard
case again. Frame rate, exposure time and mechanical isolation are decisions
that come before any of this code.
"""

import math
import os

import numpy as np
import cv2



def inject_vibration(src_path, out_path=None, freq=6.0, amp=8.0,
                     bandwidth=0.3, rot_amp=0.0, fps=None,
                     max_frames=300, seed=0):
    """Add narrow-band vibration of known frequency and amplitude.

    freq       : centre frequency in Hz (rotor/engine fundamental)
    amp        : peak displacement in pixels
    bandwidth  : 0 = pure tone; 0.3-1.0 spreads energy into neighbouring
                 frequencies, which is closer to a real machine
    rot_amp    : peak roll in degrees, if the mount transmits rotation too
    Returns (video path, ground-truth .npy path)
    """
    rng = np.random.default_rng(seed)
    if out_path is None:
        b, e = os.path.splitext(src_path)
        out_path = f"{b}_vib{freq:g}Hz_a{amp:g}{e}"

    src = VideoFileSource(src_path)
    W, H = src.width, src.height
    fps = fps or src.fps
    w = cv2.VideoWriter(out_path, cv2.VideoWriter_fourcc(*"mp4v"), fps, (W, H))

    gt, i = [], 0
    side = (freq * 0.8, freq * 1.25)          # sidebands
    while True:
        f = src.read()
        if f is None or (max_frames and i >= max_frames):
            break
        t = i / fps
        jx = amp * math.sin(2 * math.pi * freq * t)
        jy = amp * math.sin(2 * math.pi * freq * t + 1.1)
        ja = rot_amp * math.sin(2 * math.pi * freq * t + 0.4)
        for k, f2 in enumerate(side):
            jx += bandwidth * amp * math.sin(2 * math.pi * f2 * t + k)
            jy += bandwidth * amp * math.sin(2 * math.pi * f2 * t + k + 0.7)

        M = cv2.getRotationMatrix2D((W / 2.0, H / 2.0), ja, 1.0)
        M[0, 2] += jx
        M[1, 2] += jy
        w.write(cv2.warpAffine(f.image, M, (W, H),
                               borderMode=cv2.BORDER_REPLICATE))
        # store the matrix parameters, not jx/jy -- rotation about the centre
        # shows up inside tx/ty and the estimator measures it there
        gt.append([float(M[0, 2]), float(M[1, 2]),
                   float(math.atan2(M[1, 0], M[0, 0]))])
        i += 1
    w.release()
    src.release()
    gt_path = out_path + ".gt.npy"
    np.save(gt_path, np.array(gt))
    return out_path, gt_path


def vibration_sweep(src_path, cfg, freqs=(2, 4, 6, 8, 12), amp=8.0,
                    bandwidth=0.3, n=300, hf_fn=None):
    """Suppression as a function of vibration frequency.

    Pass hf_fn=hf_score (from the notebook) to reuse the same metric everything
    else is measured with.
    """
    rows = []
    print(f"{'freq':>7s} {'HF x':>8s} {'HF y':>8s} {'sat':>6s}")
    for fr in freqs:
        vid, _ = inject_vibration(src_path, freq=fr, amp=amp,
                                  bandwidth=bandwidth, max_frames=n)
        x, y, s = hf_fn(vid, cfg, n)
        print(f"{fr:5.1f}Hz {x:7.1f}% {y:7.1f}% {s:5.0f}%")
        rows.append({"freq": fr, "hf_x": x, "hf_y": y, "sat": s, "clip": vid})
    return rows


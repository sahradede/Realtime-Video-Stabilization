def plot_frequency_response(rows, title=None):
    """Suppression against vibration frequency.

    The shape is the argument: an EMA is a low-pass, so the further the
    vibration sits above the deliberate motion, the cleaner the separation.
    Handheld footage has no such separation, which is why it scores worse.
    """
    f = [r["freq"] for r in rows]
    fig, ax = plt.subplots(figsize=(9, 5))
    ax.plot(f, [r["hf_x"] for r in rows], "o-", lw=2, label="x")
    ax.plot(f, [r["hf_y"] for r in rows], "s-", lw=2, label="y")
    ax.axhspan(0, 70, color="crimson", alpha=.06)
    ax.axhspan(70, 100, color="seagreen", alpha=.06)
    ax.set_xlabel("vibration frequency (Hz)")
    ax.set_ylabel("high-frequency suppression (%)")
    ax.set_ylim(0, 100)
    ax.set_title(title or "Suppression vs vibration frequency")
    ax.legend(); ax.grid(alpha=.3)
    for r in rows:
        ax.annotate(f"{r['hf_x']:.0f}", (r["freq"], r["hf_x"]),
                    textcoords="offset points", xytext=(0, 8),
                    ha="center", fontsize=8)
    plt.tight_layout(); plt.show()


def plot_scene_comparison(results, title=None):
    """Suppression per scene, next to the clip's own measured motion.

    These two move together for a reason. On a gimbal-stabilized clip the
    measured base motion should be near zero; where it isn't, optical flow is
    tracking the scene rather than the camera, and the suppression figure for
    that clip is measuring a broken denominator.

    results: {name: {"hf_x":.., "hf_y":.., "base":..}}
    """
    names = list(results)
    idx = np.arange(len(names)); w = .35
    fig, ax = plt.subplots(1, 2, figsize=(14, 5))

    a = ax[0]
    b1 = a.bar(idx - w/2, [results[n]["hf_x"] for n in names], w,
               label="x", color="royalblue", alpha=.85)
    b2 = a.bar(idx + w/2, [results[n]["hf_y"] for n in names], w,
               label="y", color="seagreen", alpha=.85)
    for bs in (b1, b2):
        for bar in bs:
            a.text(bar.get_x()+bar.get_width()/2, bar.get_height(),
                   f"{bar.get_height():.0f}", ha="center", va="bottom", fontsize=8)
    a.set_title("Suppression by scene"); a.set_ylabel("%")
    a.set_xticks(idx); a.set_xticklabels(names); a.legend(fontsize=8)
    a.set_ylim(0, 105); a.grid(alpha=.3, axis="y")

    a = ax[1]
    base = [results[n]["base"] for n in names]
    bars = a.bar(idx, base, .5, color="darkorange", alpha=.85)
    for bar, v in zip(bars, base):
        a.text(bar.get_x()+bar.get_width()/2, bar.get_height(), f"{v:.1f}",
               ha="center", va="bottom", fontsize=9)
    a.axhline(3, ls=":", c="red", lw=1.3,
              label="above this, flow is tracking the scene")
    a.set_title("Clip's own measured motion\n(gimbal-stabilized: should be ~0)")
    a.set_ylabel("px / frame")
    a.set_xticks(idx); a.set_xticklabels(names); a.legend(fontsize=8)
    a.grid(alpha=.3, axis="y")

    fig.suptitle(title or "Scene texture drives estimation quality",
                 fontsize=13, fontweight="bold")
    plt.tight_layout(); plt.show()


def plot_correction_trace(path, cfg, freq=6.0, amp=8.0, n=120, label=None):
    """Applied correction over time, against the crop budget.

    A healthy trace oscillates around zero at the vibration frequency. A trace
    that ramps up and stays there is following something slow -- scene motion,
    not shake.
    """
    vid, _ = inject_vibration(path, freq=freq, amp=amp,
                              bandwidth=0.3, max_frames=n)
    r = stabilize_clip(vid, cfg, out_dir="trace", max_frames=n,
                       side_by_side=False, to_h264=False, quiet=True)
    co = r["corrections"]
    c = cv2.VideoCapture(path); W, H = int(c.get(3)), int(c.get(4)); c.release()
    mx, my = cfg.crop_ratio*W*0.95, cfg.crop_ratio*H*0.95

    fig, ax = plt.subplots(figsize=(11, 4))
    ax.plot(co[:, 0], lw=1.2, label="x correction")
    ax.plot(co[:, 1], lw=1.2, label="y correction")
    ax.axhline(amp, ls=":", c="gray", lw=1, label=f"injected amplitude ({amp:g}px)")
    ax.axhline(-amp, ls=":", c="gray", lw=1)
    ax.axhline(mx, ls="--", c="red", lw=.8, label=f"crop limit x ({mx:.0f}px)")
    ax.axhline(-mx, ls="--", c="red", lw=.8)
    ax.set_xlabel("frame"); ax.set_ylabel("pixels")
    ax.set_title(label or f"{os.path.basename(path)} — applied correction")
    ax.legend(fontsize=8); ax.grid(alpha=.3)
    plt.tight_layout(); plt.show()
    print(f"peak correction  x={np.abs(co[:,0]).max():.1f}px  "
          f"y={np.abs(co[:,1]).max():.1f}px   injected {amp:g}px")


